// Helper: parse "H:MM" duration string to decimal hours
function parseDuration(s: string): number {
  if (!s || s === "0:00") return 0;
  const [h, m] = s.split(":").map(Number);
  return (h || 0) + (m || 0) / 60;
}

// Helper: map CSV Frequency to ServiceCategory
function mapCategory(service: string, freq: string): ServiceCategory {
  if (service === "Commercial Cleaning") return "Commercial Cleaning";
  if (service === "Move In/Out Clean") return "Move In/Out Clean";
  if (service === "Deep Clean") return "Deep Clean";
  // Express Clean / Standard Clean → categorize by frequency
  if (freq === "Weekly") return "Weekly";
  if (freq === "Every Other Week") return "Biweekly";
  if (freq === "Every 3 Weeks") return "Triweekly";
  if (freq === "Monthly") return "Monthly";
  return "Standard Clean";
}

// Helper: map CSV Frequency to tracker frequency label
function mapFrequency(freq: string): string {
  const map: Record<string, string> = {
    "One-Time": "One Time",
    "Weekly": "Weekly",
    "Every Other Week": "Every Other Week",
    "Every 3 Weeks": "Every 3 Weeks",
    "Monthly": "Monthly",
  };
  return map[freq] ?? freq;
}

// Helper: strip leading provider ID "268: Maria Lopez" → "Maria Lopez"
function cleanerName(raw: string): string {
  if (!raw || raw === "Unassigned") return "Unassigned";
  return raw.replace(/^\d+:\s*/, "").trim();
}

